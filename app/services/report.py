"""Build the trust report: status ladder, before/after diff, remaining steps, Markdown export.

Pure functions (no network, no model calls) so they are fast and easy to test.
"""
from __future__ import annotations

import difflib
from typing import Any, Dict, List, Optional

LADDER = [
    ("generated", "Generated by Nemotron"),
    ("ai_reviewed", "Reviewed by a second Nemotron agent"),
    ("static_passed", "Verifier agent passed the fixes"),
    ("compiled", "Compiled with nvcc"),
    ("runtime_tested", "Run against reference outputs"),
    ("benchmarked", "Benchmarked on a GPU"),
]

_REMAINING = {
    "compiled": "Compile it: `nvcc -O2 -o kernel kernel.cu` (match `-arch=sm_XX` to your GPU).",
    "runtime_tested": (
        "Run it against the NumPy reference on several sizes, including sizes that are "
        "not a multiple of the block size, and compare with a tolerance."
    ),
    "benchmarked": (
        "Benchmark against a fair baseline (CuPy or PyTorch), with warm-up runs, "
        "`cudaDeviceSynchronize()` around timings, and more than one input size."
    ),
}


def ladder_progress(status: str) -> List[Dict[str, Any]]:
    """Return every rung with a `done` flag for the given verification status."""
    keys = [k for k, _ in LADDER]
    reached = keys.index(status) if status in keys else 0
    return [{"key": k, "label": label, "done": i <= reached} for i, (k, label) in enumerate(LADDER)]


def remaining_steps(status: str) -> List[str]:
    """Concrete manual steps for every rung not yet reached."""
    return [_REMAINING[r["key"]] for r in ladder_progress(status) if not r["done"] and r["key"] in _REMAINING]


def unified_diff(before: str, after: str, name: str = "kernel.cu") -> str:
    """Unified diff text (empty string when identical)."""
    diff = difflib.unified_diff(
        (before or "").splitlines(),
        (after or "").splitlines(),
        fromfile=f"{name} (translator draft)",
        tofile=f"{name} (after review/fix)",
        lineterm="",
    )
    return "\n".join(diff)


def initial_kernel(result: Dict[str, Any]) -> str:
    """The translator's first draft (iteration 0), if available."""
    for ar in result.get("agent_results", []) or []:
        if ar.get("agent") == "translator" and ar.get("success"):
            return (ar.get("sections") or {}).get("CUDA KERNEL", "")
    return ""


def models_used(result: Dict[str, Any]) -> Dict[str, str]:
    used: Dict[str, str] = {}
    for ar in result.get("agent_results", []) or []:
        used.setdefault(ar.get("agent", "?"), ar.get("model", "?"))
    return used


def build_report_markdown(
    source: str,
    result: Dict[str, Any],
    advice: Optional[Dict[str, Any]] = None,
) -> str:
    """Markdown report a user can download and attach to a PR or paper."""
    status = result.get("final_status", "generated")
    lines: List[str] = ["# CUDAify translation report", ""]
    lines += [f"**Verification status:** `{status}`  ", f"**Iterations:** {result.get('iterations', 0)}  ",
              f"**Converged:** {'yes' if result.get('converged') else 'no'}", ""]

    lines += ["## What was verified", ""]
    for rung in ladder_progress(status):
        lines.append(f"- [{'x' if rung['done'] else ' '}] {rung['label']}")
    lines.append("")

    used = models_used(result)
    if used:
        lines += ["## Models (NVIDIA Nemotron on Nebius Token Factory)", ""]
        lines += [f"- {role}: `{model}`" for role, model in used.items()]
        lines.append("")

    findings = result.get("review_findings") or []
    lines += ["## Review findings", ""]
    if findings:
        lines += ["| Severity | Category | Finding |", "|---|---|---|"]
        for f in findings:
            msg = str(f.get("message", "")).replace("|", "\\|")
            lines.append(f"| {f.get('severity', '')} | {f.get('category', '')} | {msg} |")
    else:
        lines.append("No findings reported by the final review.")
    lines.append("")

    diff = unified_diff(initial_kernel(result), result.get("final_cuda_code", ""))
    lines += ["## Changes made by the review/fix loop", ""]
    lines += ["```diff", diff, "```"] if diff else ["The reviewer made no changes to the translator's draft."]
    lines.append("")

    refs = result.get("references") or []
    if refs:
        lines += ["## References consulted by the reviewer (via Tavily)", ""]
        lines += [f"- [{r.get('title') or r.get('url')}]({r.get('url')})" for r in refs]
        lines.append("")

    if advice:
        lines += ["## Do you need custom CUDA?", "", advice.get("summary", ""), ""]
        for o in advice.get("options", []):
            lines.append(f"- **{o['name']}** ({o['fit']}): {' '.join(o['why'])}")
        lines.append("")

    todo = remaining_steps(status)
    lines += ["## Still to do before you trust this kernel", ""]
    lines += [f"{i}. {t}" for i, t in enumerate(todo, 1)] if todo else ["Nothing outstanding."]
    lines += ["", "## Original Python", "", "```python", source.strip(), "```", "",
              "---", "*AI-generated code. Compile, test, and benchmark before relying on it.*", ""]
    return "\n".join(lines)
