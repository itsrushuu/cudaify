"""Tests for the trust report builder."""
from app.services import report

RESULT = {
    "final_status": "static_passed",
    "iterations": 2,
    "converged": True,
    "final_cuda_code": "__global__ void k(int n){ if (i < n) {} }",
    "review_findings": [{"severity": "high", "category": "bounds", "message": "missing guard | here"}],
    "references": [{"title": "CUDA Best Practices", "url": "https://docs.nvidia.com/x", "snippet": "s"}],
    "agent_results": [
        {"agent": "translator", "model": "m1", "success": True,
         "sections": {"CUDA KERNEL": "__global__ void k(int n){ }"}},
        {"agent": "reviewer", "model": "m2", "success": True, "sections": {}},
    ],
}


def test_ladder_progress_marks_reached_rungs():
    rungs = report.ladder_progress("ai_reviewed")
    done = {r["key"]: r["done"] for r in rungs}
    assert done["generated"] and done["ai_reviewed"]
    assert not done["static_passed"] and not done["compiled"]


def test_unknown_status_falls_back_to_generated():
    assert [r["done"] for r in report.ladder_progress("???")][:2] == [True, False]


def test_remaining_steps_never_claims_compile():
    steps = report.remaining_steps("static_passed")
    assert len(steps) == 3 and "nvcc" in steps[0]
    assert report.remaining_steps("benchmarked") == []


def test_unified_diff():
    d = report.unified_diff("a\nb", "a\nc")
    assert "-b" in d and "+c" in d
    assert report.unified_diff("same", "same") == ""


def test_initial_kernel_and_models():
    assert "k(int n)" in report.initial_kernel(RESULT)
    assert report.models_used(RESULT) == {"translator": "m1", "reviewer": "m2"}


def test_markdown_report_contents():
    md = report.build_report_markdown("def f(): pass", RESULT, {"summary": "S", "options": []})
    assert "# CUDAify translation report" in md
    assert "[x] Generated by Nemotron" in md and "[ ] Compiled with nvcc" in md
    assert "missing guard \\| here" in md           # pipe escaped inside the table
    assert "```diff" in md and "docs.nvidia.com" in md
    assert "Still to do" in md and "AI-generated code" in md
